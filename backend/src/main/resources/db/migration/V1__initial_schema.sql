-- ASTRA Mission Database Schema
-- Version: V1 (Phase 5 - Persistence & Operational Reliability)

-- 1. Spacecraft Catalog & Vehicle Configurations
CREATE TABLE IF NOT EXISTS spacecraft_records (
    id VARCHAR(64) PRIMARY KEY,
    call_sign VARCHAR(64) NOT NULL,
    name VARCHAR(255) NOT NULL,
    model_type VARCHAR(128) NOT NULL,
    dry_mass_kg DOUBLE PRECISION NOT NULL,
    propellant_mass_kg DOUBLE PRECISION NOT NULL,
    operational_mode VARCHAR(64) NOT NULL,
    operational_status VARCHAR(64) NOT NULL,
    battery_soc_percent DOUBLE PRECISION NOT NULL,
    solar_array_watts DOUBLE PRECISION NOT NULL,
    semi_major_axis_km DOUBLE PRECISION NOT NULL,
    eccentricity DOUBLE PRECISION NOT NULL,
    inclination_deg DOUBLE PRECISION NOT NULL,
    raan_deg DOUBLE PRECISION NOT NULL,
    arg_of_perigee_deg DOUBLE PRECISION NOT NULL,
    true_anomaly_deg DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Command Audit Ledger & Idempotency Store
CREATE TABLE IF NOT EXISTS command_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command_id VARCHAR(64) NOT NULL UNIQUE,
    client_command_id VARCHAR(128),
    spacecraft_id VARCHAR(64) NOT NULL REFERENCES spacecraft_records(id) ON DELETE CASCADE,
    command_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    execution_epoch TIMESTAMP WITH TIME ZONE NOT NULL,
    operator_username VARCHAR(128),
    message TEXT NOT NULL,
    parameters_json TEXT,
    output_data_json TEXT,
    idempotent_replay BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cmd_spacecraft ON command_records(spacecraft_id);
CREATE INDEX IF NOT EXISTS idx_cmd_status ON command_records(status);
CREATE INDEX IF NOT EXISTS idx_cmd_client_id ON command_records(client_command_id);
CREATE INDEX IF NOT EXISTS idx_cmd_submitted_at ON command_records(submitted_at);

-- 3. Failure Lab Fault Lifecycle & Recovery Records
CREATE TABLE IF NOT EXISTS fault_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fault_id VARCHAR(64) NOT NULL UNIQUE,
    spacecraft_id VARCHAR(64) NOT NULL REFERENCES spacecraft_records(id) ON DELETE CASCADE,
    subsystem VARCHAR(32) NOT NULL,
    scenario_code VARCHAR(64) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    lifecycle_state VARCHAR(32) NOT NULL,
    injected_epoch TIMESTAMP WITH TIME ZONE NOT NULL,
    detected_epoch TIMESTAMP WITH TIME ZONE,
    recovered_epoch TIMESTAMP WITH TIME ZONE,
    cleared_epoch TIMESTAMP WITH TIME ZONE,
    operator_username VARCHAR(128),
    recovery_action_required VARCHAR(64),
    auto_recoverable BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    operator_explanation TEXT,
    parameters_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_fault_spacecraft ON fault_records(spacecraft_id);
CREATE INDEX IF NOT EXISTS idx_fault_subsystem ON fault_records(subsystem);
CREATE INDEX IF NOT EXISTS idx_fault_lifecycle ON fault_records(lifecycle_state);
CREATE INDEX IF NOT EXISTS idx_fault_injected_epoch ON fault_records(injected_epoch);

-- 4. Monotonic Simulation Events Audit Log
CREATE TABLE IF NOT EXISTS simulation_event_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL UNIQUE,
    sequence_number BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    simulation_epoch TIMESTAMP WITH TIME ZONE NOT NULL,
    spacecraft_id VARCHAR(64),
    summary TEXT NOT NULL,
    details_json TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_event_spacecraft ON simulation_event_records(spacecraft_id);
CREATE INDEX IF NOT EXISTS idx_event_type ON simulation_event_records(event_type);
CREATE INDEX IF NOT EXISTS idx_event_sim_epoch ON simulation_event_records(simulation_epoch);
CREATE INDEX IF NOT EXISTS idx_event_sequence ON simulation_event_records(sequence_number);

-- 5. Periodic Sampled Telemetry Archive
CREATE TABLE IF NOT EXISTS telemetry_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spacecraft_id VARCHAR(64) NOT NULL REFERENCES spacecraft_records(id) ON DELETE CASCADE,
    simulation_epoch TIMESTAMP WITH TIME ZONE NOT NULL,
    position_x DOUBLE PRECISION NOT NULL,
    position_y DOUBLE PRECISION NOT NULL,
    position_z DOUBLE PRECISION NOT NULL,
    velocity_x DOUBLE PRECISION NOT NULL,
    velocity_y DOUBLE PRECISION NOT NULL,
    velocity_z DOUBLE PRECISION NOT NULL,
    altitude_km DOUBLE PRECISION NOT NULL,
    speed_km_s DOUBLE PRECISION NOT NULL,
    in_eclipse BOOLEAN NOT NULL,
    battery_soc_percent DOUBLE PRECISION NOT NULL,
    solar_array_watts DOUBLE PRECISION NOT NULL,
    operational_mode VARCHAR(64) NOT NULL,
    operational_status VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_telem_craft_epoch ON telemetry_snapshots(spacecraft_id, simulation_epoch);

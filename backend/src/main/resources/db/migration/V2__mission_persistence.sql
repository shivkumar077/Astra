-- ASTRA Mission Universe Schema Persistence
-- Version: V2 (Durable Mission Definitions and Execution Runs)

-- 1. Mission Definitions Catalog Table
CREATE TABLE IF NOT EXISTS mission_definitions (
    id VARCHAR(64) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    destination_group VARCHAR(64) NOT NULL,
    category VARCHAR(64) NOT NULL,
    difficulty VARCHAR(64) NOT NULL,
    spacecraft_id VARCHAR(64) NOT NULL,
    duration_minutes INT NOT NULL,
    risk_level VARCHAR(32) NOT NULL,
    synopsis TEXT NOT NULL,
    objectives_json TEXT,
    completion_criteria_json TEXT,
    operational_constraints_json TEXT,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_mission_dest_group ON mission_definitions(destination_group);
CREATE INDEX IF NOT EXISTS idx_mission_category ON mission_definitions(category);
CREATE INDEX IF NOT EXISTS idx_mission_difficulty ON mission_definitions(difficulty);
CREATE INDEX IF NOT EXISTS idx_mission_spacecraft ON mission_definitions(spacecraft_id);

-- 2. Mission Execution Runs & Historical Audit Records
CREATE TABLE IF NOT EXISTS mission_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(64) NOT NULL UNIQUE,
    mission_id VARCHAR(64) NOT NULL,
    spacecraft_id VARCHAR(64) NOT NULL,
    destination VARCHAR(255),
    destination_group VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    started_epoch TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_epoch TIMESTAMP WITH TIME ZONE,
    telemetry_snapshots_captured INT NOT NULL DEFAULT 0,
    commands_dispatched INT NOT NULL DEFAULT 0,
    outcome_summary TEXT,
    objective_results_json TEXT,
    operator_username VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_run_mission_id ON mission_runs(mission_id);
CREATE INDEX IF NOT EXISTS idx_run_spacecraft ON mission_runs(spacecraft_id);
CREATE INDEX IF NOT EXISTS idx_run_status ON mission_runs(status);
CREATE INDEX IF NOT EXISTS idx_run_started_epoch ON mission_runs(started_epoch);
